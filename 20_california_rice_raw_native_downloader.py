def prism_raster_locator(zip_path):
    zip_path = Path(zip_path)

    with zipfile.ZipFile(zip_path) as z:
        names = z.namelist()

    # Current PRISM packages use GeoTIFF.
    # Keep BIL fallback for older packages if encountered.
    candidates = [
        n for n in names
        if n.lower().endswith((".tif", ".tiff"))
    ]

    if not candidates:
        candidates = [
            n for n in names
            if n.lower().endswith(".bil")
        ]

    if not candidates:
        raise RuntimeError(
            f"No GeoTIFF/BIL raster found inside PRISM ZIP: {zip_path}"
        )

    member = candidates[0]

    # absolute Linux path:
    # /vsizip//opt/.../file.zip/raster.tif
    locator = f"/vsizip/{zip_path}/{member}"

    return locator, member

def dataset_locators_for_file(local_path):
    """
    Return [(dataset_locator, package_member, primary_grid)].

    HDF/HDF-EOS:
      outer file is inspected, then every GDAL subdataset is inspected.
      The first successfully georeferenced subdataset is marked primary.

    PRISM ZIP:
      the raster inside the raw ZIP is inspected through /vsizip/.
      GeoTIFF (.tif/.tiff) is preferred; BIL is supported as a fallback.

    GeoTIFF:
      the file itself is the dataset locator.
    """
    local_path = Path(local_path)
    low = local_path.name.lower()

    if low.endswith(".zip"):
        locator, member = prism_raster_locator(local_path)
        return [(locator, member, True)]

    if low.endswith((".tif", ".tiff", ".img", ".bil", ".nc")):
        return [(str(local_path), None, True)]

    if low.endswith((".hdf", ".h4", ".hdf4", ".h5")):
        outer = run_gdalinfo_json(str(local_path))
        subs = get_subdataset_names(outer)

        if not subs:
            # Some HDFs expose a raster directly.
            return [(str(local_path), None, True)]

        return [
            (sub, None, i == 0)
            for i, sub in enumerate(subs)
        ]

    raise ValueError(
        f"Unsupported raster/package type for georef extraction: {local_path}"
    )


