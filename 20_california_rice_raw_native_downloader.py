def direct_download(
    url,
    target,
    *,
    session=None,
    verify_zip=False,
    headers=None,
):
    target = Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)

    if file_ok(target):
        print("  [EXISTS]     ", target)
        return target, False

    if target.exists() and target.stat().st_size == 0:
        print("  removing zero-byte final:", target.name)
        target.unlink()

    safe_remove_partial(target)
    part = Path(str(target) + ".part")

    s = session or requests.Session()

    with s.get(
        url,
        stream=True,
        timeout=REQUEST_TIMEOUT,
        allow_redirects=True,
        headers=headers,
    ) as r:
        r.raise_for_status()

        with part.open("wb") as f:
            for chunk in r.iter_content(chunk_size=CHUNK_BYTES):
                if chunk:
                    f.write(chunk)

    if not file_ok(part):
        raise IOError(f"Downloaded file is empty: {part}")

    if verify_zip and not zipfile.is_zipfile(part):
        head = part.read_bytes()[:200]
        part.unlink(missing_ok=True)
        raise IOError(
            "Expected ZIP but response is not a ZIP. "
            f"First bytes: {head!r}"
        )

    part.replace(target)

    print(
        "  [DOWNLOADED] ",
        target,
        f"({target.stat().st_size / 1024**2:.2f} MB)",
    )

    return target, True


class DownloadBudget:
    def __init__(self, limit=None):
        self.limit = limit
        self.new_files = 0

    def can_continue(self):
        return self.limit is None or self.new_files < self.limit

    def add(self, was_new):
        if was_new:
            self.new_files += 1


