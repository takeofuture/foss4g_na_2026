def run_gdalinfo_json(dataset_locator, timeout=180):
    """
    dataset_locator can be:
      /path/file.tif
      /path/file.hdf
      HDF4_EOS:EOS_GRID:"/path/file.hdf":...
      /vsizip//path/file.zip/raster.tif
    """
    cmd = ["gdalinfo", "-json", str(dataset_locator)]

    p = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=timeout,
    )

    if p.returncode != 0:
        raise RuntimeError(
            f"gdalinfo failed for {dataset_locator}\n"
            f"stderr:\n{p.stderr[-4000:]}"
        )

    return json.loads(p.stdout)


def get_subdataset_names(info):
    md = info.get("metadata") or {}
    sub = md.get("SUBDATASETS") or {}

    names = []
    for k, v in sub.items():
        if k.startswith("SUBDATASET_") and k.endswith("_NAME"):
            names.append(v)

    def sub_num(s):
        # Stable sort by SUBDATASET number if possible is not available here,
        # so preserve GDAL JSON insertion order.
        return 0

    return names


def wgs84_extent_from_info(info):
    ext = info.get("wgs84Extent")
    if ext is None:
        return None
    return ext


def native_bounds_from_info(info):
    cc = info.get("cornerCoordinates") or {}

    if cc:
        return cc

    gt = info.get("geoTransform")
    size = info.get("size")

    if gt and size and len(size) >= 2:
        width, height = size[0], size[1]
        x0, a, b, y0, d, e = gt

        pts = []
        for col, row in [(0,0), (width,0), (width,height), (0,height)]:
            x = x0 + col*a + row*b
            y = y0 + col*d + row*e
            pts.append([x, y])

        return {
            "computed_corners": pts
        }

    return None


def pixel_size_from_info(info):
    gt = info.get("geoTransform")
    if not gt:
        return None, None

    # For north-up grids these are exact. For rotated grids the full transform
    # is also stored, so later code should use the transform itself.
    return gt[1], gt[5]


