def month_start_end(year, month):
    start = date(year, month, 1)
    last = calendar.monthrange(year, month)[1]
    end = date(year, month, last)
    return start.isoformat(), end.isoformat()


def granule_urls(granule):
    # Prefer external HTTPS URLs for EC2 process.
    for access in ("external", None):
        try:
            if access is None:
                urls = list(granule.data_links())
            else:
                urls = list(granule.data_links(access=access))
            if urls:
                return urls
        except Exception:
            pass
    return []


def science_url_and_filename(granule):
    """
    Return ONLY the primary science raster URL.
    For the MODIS products used here this should be .hdf.
    Ancillary BROWSE JPG and CMR XML links are deliberately ignored.
    """
    urls = granule_urls(granule)

    # Strictly prefer HDF for these MODIS products.
    for ext in (".hdf", ".h5", ".nc"):
        for url in urls:
            name = unquote(Path(urlparse(url).path).name)
            if name.lower().endswith(ext):
                return url, name

    return None, None


def granule_filename(granule):
    _, filename = science_url_and_filename(granule)

    if filename:
        return filename

    # Fallback metadata only; no download is attempted without a science URL.
    try:
        return str(granule["umm"]["GranuleUR"])
    except Exception:
        pass

    try:
        return str(granule["meta"]["native-id"])
    except Exception:
        pass

    return None


def granule_temporal(granule):
    try:
        rng = granule["umm"]["TemporalExtent"]["RangeDateTime"]
        return rng.get("BeginningDateTime"), rng.get("EndingDateTime")
    except Exception:
        return None, None


def acquisition_date_from_granule(granule, filename=None):
    """
    Prefer CMR BeginningDateTime.
    Fall back to MODIS AYYYYDDD embedded in the filename.
    """
    t0, _ = granule_temporal(granule)

    if t0:
        try:
            return pd.to_datetime(t0, utc=True).date()
        except Exception:
            pass

    filename = filename or granule_filename(granule) or ""

    m = re.search(r"\.A(\d{4})(\d{3})\.", filename)
    if m:
        year = int(m.group(1))
        doy = int(m.group(2))
        return date(year, 1, 1) + timedelta(days=doy - 1)

    return None


def save_cmr_inventory(product_key, year, month, granules):
    out_dir = MANIFEST_DIR / "cmr_inventory" / product_key
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = []

    for g in granules:
        science_url, filename = science_url_and_filename(g)
        t0, t1 = granule_temporal(g)
        acq = acquisition_date_from_granule(g, filename)

        rows.append({
            "filename": filename,
            "science_url": science_url,
            "time_start": t0,
            "time_end": t1,
            "acquisition_date": acq.isoformat() if acq else None,
            "size_mb": getattr(g, "size", None),
        })

    fp = out_dir / f"{year}_{month:02d}.json"

    fp.write_text(
        json.dumps(
            rows,
            indent=2,
            ensure_ascii=False,
            default=str,
        ),
        encoding="utf-8",
    )

    return fp


