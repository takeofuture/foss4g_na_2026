    dest = (
        RAW_DIR
        / "nasa_modis"
        / product_key
        / str(acq_date.year)
        / f"{acq_date.month:02d}"
    )
    dest.mkdir(parents=True, exist_ok=True)

    target = dest / filename

    if file_ok(target):
        print("[EXISTS]", target)
        register_nasa_existing(product_key, target)

        ensure_spatial_metadata(
            source="NASA_Earthdata",
            product=product_key,
            local_path=target,
            time_start=t0,
            time_end=t1,
            tile=modis_tile_from_filename(filename),
        )

        return False

    print(
        "[GET HDF ONLY]",
        spec["short_name"],
        acq_date.isoformat(),
        filename,
    )

    # Authenticated direct HTTPS download of ONLY the selected science URL.
    target, was_new = direct_download(
        remote_url,
        target,
        session=NASA_SESSION,
    )

    register_nasa_existing(product_key, target)

    record_manifest(
        source="NASA_Earthdata",
        product=product_key,
        remote_id=filename,
        remote_url=remote_url,
        local_path=target,
        time_start=t0,
        time_end=t1,
        native_resolution=spec["nominal_resolution"],
        extra={
            "short_name": spec["short_name"],
            "version": spec["version"],
            "cmr_bbox_query": CA_BBOX,
            "acquisition_date": acq_date.isoformat(),
            "global_dedup": True,
            "science_file_only": True,
        },
    )

    ensure_spatial_metadata(
        source="NASA_Earthdata",
        product=product_key,
        local_path=target,
        time_start=t0,
        time_end=t1,
        tile=modis_tile_from_filename(filename),
    )

    return was_new


