"""## 6. PRISM daily 4 km raw grid packages

The official PRISM web service returns **one raw grid package per request**.

This script keeps the original PRISM ZIP package unchanged. Current PRISM packages contain a GeoTIFF raster; the locator also supports BIL as a fallback for older package layouts. Ancillary information is preserved exactly as distributed, such as:

- `.tif` / `.tiff` (current raster payload)
- `.bil` / `.hdr` when present in older packages
- `.prj`
- `.info.txt`
- station list files
- XML metadata

That is useful for later local alignment/processing.

**Important resume behavior:** PRISM documents that repeated downloads of the same file within 24 hours are restricted. Therefore this branch always checks local EC2 storage first and does **not** contact PRISM when the file already exists.

The official bulk example sleeps 2 seconds between requests; this script uses 2.1 seconds.
"""

def seasonal_dates(year):
    for month in MONTHS:
        last = calendar.monthrange(year, month)[1]
        for day in range(1, last + 1):
            yield date(year, month, day)


def prism_url(element, dt):
    return f"{PRISM_BASE}/{element}/{dt.strftime('%Y%m%d')}"


def run_prism():
    if not ENABLE_PRISM:
        return

    print("\n========== PRISM DAILY 4 km RAW ==========")

    if RUN_MODE == "smoke":
        work = [
            (SMOKE_PRISM_ELEMENT, SMOKE_PRISM_DATE)
        ]
    else:
        work = (
            (element, dt)
            for year in range(START_YEAR, END_YEAR + 1)
            for dt in seasonal_dates(year)
            for element in PRISM_ELEMENTS
        )

    for element, dt in work:
        if not budget.can_continue():
            print("Reached MAX_NEW_FILES_PER_RUN")
            return

        filename = (
            f"prism_{element}_4km_{dt.strftime('%Y%m%d')}.zip"
        )

        target = (
            RAW_DIR
            / "prism_daily_4km"
            / element
            / str(dt.year)
            / f"{dt.month:02d}"
            / filename
        )

        url = prism_url(element, dt)

        if file_ok(target):
            print("[EXISTS]", target)
            record_manifest(
                source="PRISM_Climate_Group",
                product=f"prism_{element}",
                remote_id=dt.isoformat(),
                remote_url=url,
                local_path=target,
                time_start=dt.isoformat(),
                time_end=dt.isoformat(),
                native_resolution="4 km",
                extra={
                    "package": "raw ZIP with GeoTIFF/BIL raster + metadata",
                },
            )

            ensure_spatial_metadata(
                source="PRISM_Climate_Group",
                product=f"prism_{element}",
                local_path=target,
                time_start=dt.isoformat(),
                time_end=dt.isoformat(),
                tile=None,
            )

            continue

        try:
            print("[GET]", element, dt.isoformat())

            target, was_new = direct_download(
                url,
                target,
                verify_zip=True,
            )

            record_manifest(
                source="PRISM_Climate_Group",
                product=f"prism_{element}",
                remote_id=dt.isoformat(),
                remote_url=url,
                local_path=target,
                time_start=dt.isoformat(),
                time_end=dt.isoformat(),
                native_resolution="4 km",
                extra={
                    "package": "raw ZIP with GeoTIFF/BIL raster + metadata",
                },
            )

            ensure_spatial_metadata(
                source="PRISM_Climate_Group",
                product=f"prism_{element}",
                local_path=target,
                time_start=dt.isoformat(),
                time_end=dt.isoformat(),
                tile=None,
            )

            budget.add(was_new)

            if was_new:
                time.sleep(PRISM_SLEEP_SECONDS)

        except Exception as e:
            print(
                "  PRISM ERROR:",
                element,
                dt.isoformat(),
                repr(e),
            )
            record_error(
                "PRISM_Climate_Group",
                f"prism_{element}",
                dt.isoformat(),
                e,
                {"url": url},
            )
            # Avoid rapid-fire retries against the service.
            time.sleep(PRISM_SLEEP_SECONDS)

