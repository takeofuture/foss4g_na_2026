def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            b = f.read(8 * 1024 * 1024)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def atomic_json(path: Path, obj: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(str(path) + ".part")
    tmp.unlink(missing_ok=True)
    tmp.write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(path)


def atomic_csv_rows(path: Path, rows: List[dict], fields: List[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(str(path) + ".part")
    tmp.unlink(missing_ok=True)
    with tmp.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    tmp.replace(path)


def atomic_dataframe_csv(df: pd.DataFrame, path: Path) -> None:
    tmp = Path(str(path) + ".part")
    tmp.unlink(missing_ok=True)
    df.to_csv(tmp, index=False)
    tmp.replace(path)


def atomic_dataframe_parquet(df: pd.DataFrame, path: Path) -> None:
    tmp = Path(str(path) + ".part")
    tmp.unlink(missing_ok=True)
    df.to_parquet(tmp, index=False)
    tmp.replace(path)


def write_dataframe_pair(df: pd.DataFrame, csv_path: Path, parquet_path: Path) -> None:
    atomic_dataframe_csv(df, csv_path)
    atomic_dataframe_parquet(df, parquet_path)


