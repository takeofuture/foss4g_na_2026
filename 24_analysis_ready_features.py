def expected_prism_keys() -> set[Tuple[str, str]]:
    out: set[Tuple[str, str]] = set()
    for year in range(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR + 1):
        for month in MONTHS:
            last = calendar.monthrange(year, month)[1]
            for day in range(1, last + 1):
                d = date(year, month, day).isoformat()
                for element in PRISM_ELEMENTS:
                    out.add((element, d))
    return out


def parse_prism_date(path: str) -> date:
    m = re.search(r"(20\d{6})", Path(path).name)
    if not m:
        raise ValueError(f"Cannot infer YYYYMMDD from PRISM filename: {path}")
    return datetime.strptime(m.group(1), "%Y%m%d").date()


def load_prism_records() -> List[PrismRecord]:
    by_key: Dict[Tuple[str, str], PrismRecord] = {}
    duplicate_keys: List[Tuple[str, str]] = []

    with BAND_MANIFEST.open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            product = str(row.get("product") or "").strip().lower()
            if not product.startswith("prism_"):
                continue
            element = product.removeprefix("prism_")
            if element not in PRISM_ELEMENTS:
                continue
            local_path = str(row.get("local_path") or "").strip()
            locator = str(row.get("dataset_locator") or "").strip()
            if not local_path or not locator:
                continue
            dt = parse_prism_date(local_path)
            if dt.year < ANALYSIS_START_YEAR or dt.year > ANALYSIS_END_YEAR or dt.month not in MONTH_SET:
                continue

            rec = PrismRecord(
                element=element,
                dt=dt,
                local_path=local_path,
                dataset_locator=locator,
                band_index=safe_int(row.get("band_index"), 1),
                source_nodata=safe_float(row.get("no_data_value")),
                source_scale=safe_float(row.get("scale")),
                source_offset=safe_float(row.get("offset")),
                source_unit=str(row.get("unit") or "").strip(),
            )
            key = (element, dt.isoformat())
            old = by_key.get(key)
            if old is not None and old.local_path != rec.local_path:
                duplicate_keys.append(key)
            by_key[key] = rec

    if duplicate_keys:
        raise RuntimeError(f"Duplicate PRISM date/element keys in band manifest, first examples: {duplicate_keys[:10]}")

    expected = expected_prism_keys()
    actual = set(by_key)
    missing = sorted(expected - actual)
    extra = sorted(actual - expected)
    if missing:
        raise RuntimeError(
            f"PRISM inventory incomplete for 2007-2025 Apr-Nov: missing {len(missing)} daily element files. "
            f"First missing: {missing[:20]}"
        )
    if extra:
        print(f"[NOTE] Ignoring {len(extra)} extra PRISM keys outside expected inventory")

    return [by_key[k] for k in sorted(expected, key=lambda x: (x[1], x[0]))]


