def load_prism_observations() -> Tuple[List[dict], int]:
    dedup: Dict[str, dict] = {}
    malformed = 0
    if PRISM_OBS_JSONL.exists():
        with PRISM_OBS_JSONL.open("r", encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    r = json.loads(line)
                    k = str(r.get("record_key") or "")
                    if k:
                        dedup[k] = r
                except Exception:
                    malformed += 1
    rows = sorted(dedup.values(), key=lambda r: (r["date"], r["element"], r["local_path"]))
    return rows, malformed


def aggregate_numeric_group(g: pd.DataFrame, aggregation: str) -> Tuple[float, float]:
    wm = pd.to_numeric(g["weighted_mean"], errors="coerce")
    if aggregation == "sum":
        value = wm.sum(min_count=1)
        return (float(value) if pd.notna(value) else math.nan, float(wm.notna().sum()))

    den = pd.to_numeric(g["valid_weight_m2"], errors="coerce")
    num = pd.to_numeric(g["sum_wx"], errors="coerce")
    ok = den.notna() & num.notna() & (den > 0)
    den_sum = den[ok].sum()
    if not math.isfinite(float(den_sum)) or float(den_sum) <= 0:
        return math.nan, 0.0
    return float(num[ok].sum() / den_sum), float(den_sum)


def satellite_feature_name(product: str, variable: str) -> str:
    special = {
        ("mod17_gpp", "gpp"): "gpp_mod17",
        ("mod17_gpp", "psn_net"): "psn_net_mod17",
        ("umt_gpp", "gpp_ntsg"): "gpp_ntsg",
    }
    return special.get((product, variable), variable)


def aggregate_satellite_monthly(df: pd.DataFrame, *, tile_mode: bool = False) -> pd.DataFrame:
    numeric_cols = ["year", "month", "valid_weight_m2", "sum_wx", "weighted_mean", "coverage_fraction"]
    for c in numeric_cols:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df[(df["year"].between(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR)) & (df["month"].isin(MONTHS))].copy()

    keys = ["year", "month"] + (["tile"] if tile_mode else []) + ["product", "variable"]
    rows: List[dict] = []
    for key, g in df.groupby(keys, dropna=False, sort=True):
        if not isinstance(key, tuple):
            key = (key,)
        d = dict(zip(keys, key))
        aggs = {str(x) for x in g["temporal_aggregation"].dropna().unique()}
        if len(aggs) != 1:
            raise RuntimeError(f"Inconsistent temporal_aggregation for {d}: {sorted(aggs)}")
        agg = next(iter(aggs))
        value, temporal_weight = aggregate_numeric_group(g, agg)
        cov = pd.to_numeric(g["coverage_fraction"], errors="coerce")
        out = {
            **d,
            "feature": satellite_feature_name(str(d["product"]), str(d["variable"])),
            "value": value,
            "unit": str(g["output_unit"].dropna().iloc[0]) if g["output_unit"].notna().any() else "",
            "temporal_aggregation": agg,
            "temporal_weight": temporal_weight,
            "observation_count": int(len(g)),
            "valid_observation_count": int(pd.to_numeric(g["weighted_mean"], errors="coerce").notna().sum()),
            "coverage_mean": float(cov.mean()) if cov.notna().any() else math.nan,
            "coverage_min": float(cov.min()) if cov.notna().any() else math.nan,
            "source_family": "satellite",
        }
        rows.append(out)
    return pd.DataFrame(rows)


def aggregate_prism_monthly(prism_daily: pd.DataFrame) -> pd.DataFrame:
    for c in ("year", "month", "valid_weight_m2", "sum_wx", "weighted_mean", "coverage_fraction"):
        prism_daily[c] = pd.to_numeric(prism_daily[c], errors="coerce")
    rows: List[dict] = []
    for (year, month, element), g in prism_daily.groupby(["year", "month", "element"], sort=True):
        agg = PRISM_MONTHLY_AGG[str(element)]
        value, temporal_weight = aggregate_numeric_group(g, agg)
        cov = pd.to_numeric(g["coverage_fraction"], errors="coerce")
        rows.append({
            "year": int(year),
            "month": int(month),
            "product": "prism_daily_4km",
            "variable": str(element),
            "feature": PRISM_FEATURE_NAMES[str(element)],
            "value": value,
            "unit": "mm/month" if element == "ppt" else PRISM_UNITS[str(element)],
            "temporal_aggregation": agg,
            "temporal_weight": temporal_weight,
            "observation_count": int(len(g)),
            "valid_observation_count": int(pd.to_numeric(g["weighted_mean"], errors="coerce").notna().sum()),
            "coverage_mean": float(cov.mean()) if cov.notna().any() else math.nan,
            "coverage_min": float(cov.min()) if cov.notna().any() else math.nan,
            "source_family": "climate",
        })
    return pd.DataFrame(rows)


def build_seasonal_long(monthly_long: pd.DataFrame) -> pd.DataFrame:
    rows: List[dict] = []
    for (year, feature), g in monthly_long.groupby(["year", "feature"], sort=True):
        aggs = {str(x) for x in g["temporal_aggregation"].dropna().unique()}
        if len(aggs) != 1:
            raise RuntimeError(f"Inconsistent seasonal aggregation for {year}/{feature}: {sorted(aggs)}")
        agg = next(iter(aggs))
        val = pd.to_numeric(g["value"], errors="coerce")
        tw = pd.to_numeric(g["temporal_weight"], errors="coerce")
        if agg == "sum":
            v = val.sum(min_count=1)
            seasonal_value = float(v) if pd.notna(v) else math.nan
            seasonal_weight = float(val.notna().sum())
        else:
            ok = val.notna() & tw.notna() & (tw > 0)
            if ok.any() and float(tw[ok].sum()) > 0:
                seasonal_value = float((val[ok] * tw[ok]).sum() / tw[ok].sum())
                seasonal_weight = float(tw[ok].sum())
            elif val.notna().any():
                seasonal_value = float(val.mean())
                seasonal_weight = float(val.notna().sum())
            else:
                seasonal_value = math.nan
                seasonal_weight = 0.0
        cov = pd.to_numeric(g["coverage_mean"], errors="coerce")
        first = g.iloc[0]
        rows.append({
            "year": int(year),
            "feature": feature,
            "value": seasonal_value,
            "unit": first["unit"],
            "temporal_aggregation": agg,
            "temporal_weight": seasonal_weight,
            "months_present": int(g.loc[val.notna(), "month"].nunique()),
            "coverage_mean": float(cov.mean()) if cov.notna().any() else math.nan,
            "source_family": first["source_family"],
            "product": first["product"],
            "variable": first["variable"],
        })
    return pd.DataFrame(rows)


def load_rice_area() -> pd.DataFrame:
    a = pd.read_csv(STEP21_AREA_CSV)
    a["year"] = pd.to_numeric(a["year"], errors="coerce").astype("Int64")
    a = a[a["year"].between(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR)].copy()
    expected = set(range(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR + 1))
    actual = set(int(x) for x in a["year"].dropna())
    if actual != expected:
        raise RuntimeError(f"Step-21 rice area years mismatch. Missing: {sorted(expected - actual)}")
    out = a[["year", "rice_pixels", "rice_area_hectares_if_meters", "rice_area_acres_if_meters"]].copy()
    out = out.rename(columns={
        "rice_pixels": "cdl_rice_pixels",
        "rice_area_hectares_if_meters": "cdl_rice_area_hectares",
        "rice_area_acres_if_meters": "cdl_rice_area_acres",
    })
    if pd.to_numeric(out["cdl_rice_area_acres"], errors="coerce").isna().any():
        raise RuntimeError("Step-21 rice_area_acres is missing; expected projected-meter CDL masks.")
    out["year"] = out["year"].astype(int)
    return out


def complete_month_index() -> pd.DataFrame:
    return pd.DataFrame(
        [(y, m) for y in range(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR + 1) for m in MONTHS],
        columns=["year", "month"],
    )


def build_wide(monthly_long: pd.DataFrame, rice_area: pd.DataFrame) -> pd.DataFrame:
    wide = monthly_long.pivot(index=["year", "month"], columns="feature", values="value").reset_index()
    wide.columns.name = None
    wide = complete_month_index().merge(wide, on=["year", "month"], how="left")
    wide = wide.merge(rice_area, on="year", how="left")
    return wide.sort_values(["year", "month"]).reset_index(drop=True)


def build_seasonal_wide(seasonal_long: pd.DataFrame, rice_area: pd.DataFrame) -> pd.DataFrame:
    wide = seasonal_long.pivot(index="year", columns="feature", values="value").reset_index()
    wide.columns.name = None
    years = pd.DataFrame({"year": list(range(ANALYSIS_START_YEAR, ANALYSIS_END_YEAR + 1))})
    wide = years.merge(wide, on="year", how="left").merge(rice_area, on="year", how="left")
    return wide.sort_values("year").reset_index(drop=True)


def build_feature_dictionary(monthly_long: pd.DataFrame) -> pd.DataFrame:
    cols = ["feature", "source_family", "product", "variable", "unit", "temporal_aggregation"]
    d = monthly_long[cols].drop_duplicates().sort_values("feature").reset_index(drop=True)
    descriptions = {
        "gpp_ntsg": "UMT/NTSG GPP; kept separate from MOD17; no cross-product gap filling",
        "gpp_mod17": "MOD17 GPP; kept separate from NTSG; no cross-product gap filling",
        "ppt_mm": "PRISM daily precipitation summed within month/season",
        "ndwi": "MOD09 per-pixel normalized difference (green-nir)/(green+nir), after QA",
        "mndwi": "MOD09 per-pixel normalized difference (green-swir1)/(green+swir1), after QA",
        "ndmi": "MOD09 per-pixel normalized difference (nir-swir1)/(nir+swir1), after QA",
    }
    d["notes"] = d["feature"].map(descriptions).fillna("")
    rice_rows = pd.DataFrame([
        {"feature": "cdl_rice_area_acres", "source_family": "landcover", "product": "USDA_CDL", "variable": "rice_area", "unit": "acres", "temporal_aggregation": "annual", "notes": "Actual annual CDL class-3 rice area; no proxy year"},
        {"feature": "cdl_rice_area_hectares", "source_family": "landcover", "product": "USDA_CDL", "variable": "rice_area", "unit": "hectares", "temporal_aggregation": "annual", "notes": "Actual annual CDL class-3 rice area; no proxy year"},
        {"feature": "cdl_rice_pixels", "source_family": "landcover", "product": "USDA_CDL", "variable": "rice_pixels", "unit": "30m pixels", "temporal_aggregation": "annual", "notes": "Actual annual CDL class-3 pixel count"},
    ])
    return pd.concat([d, rice_rows], ignore_index=True)


def build_quality(monthly_long: pd.DataFrame) -> pd.DataFrame:
    idx = complete_month_index()
    rows: List[dict] = []
    expected_n = len(idx)
    for feature, g in monthly_long.groupby("feature", sort=True):
        merged = idx.merge(g[["year", "month", "value", "coverage_mean"]], on=["year", "month"], how="left")
        value = pd.to_numeric(merged["value"], errors="coerce")
        cov = pd.to_numeric(merged["coverage_mean"], errors="coerce")
        rows.append({
            "feature": feature,
            "expected_year_months": expected_n,
            "nonmissing_year_months": int(value.notna().sum()),
            "missing_year_months": int(value.isna().sum()),
            "coverage_mean": float(cov.mean()) if cov.notna().any() else math.nan,
            "coverage_min": float(cov.min()) if cov.notna().any() else math.nan,
        })
    return pd.DataFrame(rows)


