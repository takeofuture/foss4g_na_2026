def validate_signature(records: List[PrismRecord], reset: bool) -> None:
    if reset:
        reset_step24_work()
    current = run_signature(records)
    if RUN_SIGNATURE_JSON.exists():
        old = json.loads(RUN_SIGNATURE_JSON.read_text(encoding="utf-8"))
        if old != current:
            raise RuntimeError(
                "Existing Step-24 PRISM checkpoint has a different input/code signature. "
                "Run with --reset-prism-work to intentionally rebuild it."
            )
    else:
        atomic_json(RUN_SIGNATURE_JSON, current)


def clamp_window(window: Window, width: int, height: int) -> Optional[Window]:
    col0 = max(0, int(math.floor(window.col_off)))
    row0 = max(0, int(math.floor(window.row_off)))
    col1 = min(width, int(math.ceil(window.col_off + window.width)))
    row1 = min(height, int(math.ceil(window.row_off + window.height)))
    if col1 <= col0 or row1 <= row0:
        return None
    return Window(col0, row0, col1 - col0, row1 - row0)


def positive_data_window(ds, threshold: float = 0.0, nodata: Optional[float] = None) -> Optional[Window]:
    min_row, min_col = ds.height, ds.width
    max_row = max_col = -1
    for _, w in ds.block_windows(1):
        a = ds.read(1, window=w)
        good = np.isfinite(a) & (a > threshold)
        if nodata is not None:
            good &= a != nodata
        rr, cc = np.where(good)
        if rr.size == 0:
            continue
        min_row = min(min_row, int(w.row_off) + int(rr.min()))
        max_row = max(max_row, int(w.row_off) + int(rr.max()))
        min_col = min(min_col, int(w.col_off) + int(cc.min()))
        max_col = max(max_col, int(w.col_off) + int(cc.max()))
    if max_row < 0:
        return None
    return Window(min_col, min_row, max_col - min_col + 1, max_row - min_row + 1)


def annual_mask_path(year: int) -> Path:
    return STEP21_MASK_DIR / str(year) / f"rice_mask_{year}.tif"


def rice_positive_bounds(year: int) -> Tuple[float, float, float, float]:
    if year in _MASK_BOUNDS_CACHE:
        return _MASK_BOUNDS_CACHE[year]
    p = annual_mask_path(year)
    if not p.exists():
        raise FileNotFoundError(f"Missing actual annual CDL rice mask: {p}")
    with rasterio.open(p) as ds:
        w = positive_data_window(ds, threshold=0.0, nodata=STEP21_MASK_NODATA)
        if w is None:
            raise RuntimeError(f"No rice pixels in annual mask: {p}")
        b = rasterio.windows.bounds(w, ds.transform)
        _MASK_BOUNDS_CACHE[year] = b
        return b


def grid_hash(ds) -> str:
    payload = {
        "crs": ds.crs.to_wkt() if ds.crs else "",
        "transform": [float(x) for x in tuple(ds.transform)],
        "width": int(ds.width),
        "height": int(ds.height),
    }
    return hashlib.sha1(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()[:16]


def pixel_area_for_window(ds, window: Window) -> np.ndarray | float:
    if ds.crs is None:
        raise RuntimeError(f"Raster has no CRS: {ds.name}")
    pycrs = PyCRS.from_user_input(ds.crs)
    if pycrs.is_projected:
        factor = 1.0
        try:
            if pycrs.axis_info and pycrs.axis_info[0].unit_conversion_factor:
                factor = float(pycrs.axis_info[0].unit_conversion_factor)
        except Exception:
            pass
        det = abs(ds.transform.a * ds.transform.e - ds.transform.b * ds.transform.d)
        return float(det * factor * factor)

    if not pycrs.is_geographic:
        raise RuntimeError(f"Unsupported CRS for area weighting: {ds.crs}")
    if abs(ds.transform.b) > 1e-12 or abs(ds.transform.d) > 1e-12:
        raise RuntimeError("Rotated geographic PRISM grid is not supported")

    geod = pycrs.get_geod()
    col0 = int(window.col_off)
    row0 = int(window.row_off)
    height = int(window.height)
    x_left = ds.transform.c + col0 * ds.transform.a
    x_right = ds.transform.c + (col0 + 1) * ds.transform.a
    areas = np.empty((height, 1), dtype="float64")
    for i in range(height):
        r = row0 + i
        y_top = ds.transform.f + r * ds.transform.e
        y_bottom = ds.transform.f + (r + 1) * ds.transform.e
        a, _ = geod.polygon_area_perimeter(
            [x_left, x_right, x_right, x_left],
            [y_top, y_top, y_bottom, y_bottom],
        )
        areas[i, 0] = abs(float(a))
    return areas


def fraction_cache_path(year: int, ds) -> Path:
    return CACHE_DIR / str(year) / f"rice_fraction_{year}_{grid_hash(ds)}.tif"


def build_or_load_fraction(year: int, ds) -> FractionBundle:
    gh = grid_hash(ds)
    key = (year, gh)
    if key in _FRACTION_MEM:
        return _FRACTION_MEM[key]

    target = fraction_cache_path(year, ds)
    if not target.exists() or target.stat().st_size == 0:
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = Path(str(target) + ".part")
        tmp.unlink(missing_ok=True)
        mask_path = annual_mask_path(year)
        if not mask_path.exists():
            raise FileNotFoundError(f"Missing Step-21 rice mask: {mask_path}")
        if ds.crs is None:
            raise RuntimeError(f"PRISM raster has no CRS: {ds.name}")

        with rasterio.open(mask_path) as src:
            rb = rice_positive_bounds(year)
            rb_dst = transform_bounds(src.crs, ds.crs, *rb, densify_pts=21)
            fw = from_bounds(*rb_dst, transform=ds.transform)
            fw = Window(fw.col_off - 1, fw.row_off - 1, fw.width + 2, fw.height + 2)
            w = clamp_window(fw, ds.width, ds.height)
            if w is None:
                raise RuntimeError(f"Annual rice area does not overlap PRISM grid for {year}")

            dst_transform = window_transform(w, ds.transform)
            dst = np.full((int(w.height), int(w.width)), FRACTION_NODATA, dtype="float32")
            reproject(
                source=rasterio.band(src, 1),
                destination=dst,
                src_transform=src.transform,
                src_crs=src.crs,
                src_nodata=STEP21_MASK_NODATA,
                dst_transform=dst_transform,
                dst_crs=ds.crs,
                dst_nodata=FRACTION_NODATA,
                resampling=Resampling.average,
                init_dest_nodata=True,
                num_threads=2,
            )
            valid = np.isfinite(dst) & (dst != FRACTION_NODATA)
            dst[valid] = np.clip(dst[valid], 0.0, 1.0)
            pos = valid & (dst > RICE_FRACTION_MIN)
            rr, cc = np.where(pos)
            if rr.size == 0:
                raise RuntimeError(f"No positive rice fraction on PRISM grid for {year}")
            r0, r1 = int(rr.min()), int(rr.max()) + 1
            c0, c1 = int(cc.min()), int(cc.max()) + 1
            trimmed = dst[r0:r1, c0:c1]
            w2 = Window(int(w.col_off) + c0, int(w.row_off) + r0, c1 - c0, r1 - r0)
            out_transform = window_transform(w2, ds.transform)

            profile = {
                "driver": "GTiff",
                "width": int(w2.width),
                "height": int(w2.height),
                "count": 1,
                "dtype": "float32",
                "crs": ds.crs,
                "transform": out_transform,
                "nodata": FRACTION_NODATA,
                "compress": "DEFLATE",
                "predictor": 3,
                "BIGTIFF": "IF_SAFER",
            }
            with rasterio.open(tmp, "w", **profile) as out:
                out.write(trimmed.astype("float32"), 1)
                out.update_tags(
                    source_mask=str(mask_path),
                    year=str(year),
                    target_product="prism_daily_4km",
                    target_grid_hash=gh,
                    target_row_off=str(int(w2.row_off)),
                    target_col_off=str(int(w2.col_off)),
                    target_full_width=str(ds.width),
                    target_full_height=str(ds.height),
                )
        tmp.replace(target)
        print(f"[CACHE PRISM RICE FRACTION] {target}")

    with rasterio.open(target) as frac_ds:
        tags = frac_ds.tags()
        w = Window(
            int(tags["target_col_off"]),
            int(tags["target_row_off"]),
            frac_ds.width,
            frac_ds.height,
        )
        frac = frac_ds.read(1).astype("float32")
        good = np.isfinite(frac) & (frac != FRACTION_NODATA)
        frac[~good] = 0.0
        frac = np.clip(frac, 0.0, 1.0)

    area = pixel_area_for_window(ds, w)
    weights = frac.astype("float64") * area
    bundle = FractionBundle(
        fraction=frac,
        window=w,
        pixel_area=area,
        rice_area_m2_total=float(np.sum(weights, dtype=np.float64)),
        cache_path=str(target),
    )
    _FRACTION_MEM[key] = bundle
    return bundle


def grids_match_fraction_cache(ds, bundle: FractionBundle, year: int) -> bool:
    # Cache key already includes exact target grid hash; this helper documents
    # that each daily file must use the same grid as the bundle selected for it.
    return fraction_cache_path(year, ds).resolve() == Path(bundle.cache_path).resolve()


def weighted_stats(values: np.ndarray, valid: np.ndarray, bundle: FractionBundle) -> dict:
    frac = bundle.fraction
    rice = np.isfinite(frac) & (frac > RICE_FRACTION_MIN)
    good = rice & valid & np.isfinite(values)
    if np.isscalar(bundle.pixel_area):
        weights = frac.astype("float64") * float(bundle.pixel_area)
    else:
        weights = frac.astype("float64") * bundle.pixel_area

    total = float(np.sum(weights[rice], dtype=np.float64)) if np.any(rice) else 0.0
    if not np.any(good):
        return {
            "rice_area_m2_total": total,
            "valid_weight_m2": 0.0,
            "coverage_fraction": 0.0,
            "sum_wx": 0.0,
            "sum_wx2": 0.0,
            "weighted_mean": None,
            "value_min": None,
            "value_max": None,
            "valid_cells": 0,
            "rice_cells": int(np.count_nonzero(rice)),
        }

    w = weights[good]
    x = values[good].astype("float64")
    den = float(np.sum(w, dtype=np.float64))
    num = float(np.sum(w * x, dtype=np.float64))
    return {
        "rice_area_m2_total": total,
        "valid_weight_m2": den,
        "coverage_fraction": den / total if total > 0 else None,
        "sum_wx": num,
        "sum_wx2": float(np.sum(w * x * x, dtype=np.float64)),
        "weighted_mean": num / den if den > 0 else None,
        "value_min": float(np.min(x)),
        "value_max": float(np.max(x)),
        "valid_cells": int(np.count_nonzero(good)),
        "rice_cells": int(np.count_nonzero(rice)),
    }


def process_prism_record(rec: PrismRecord) -> dict:
    p = Path(rec.local_path)
    if not p.exists() or p.stat().st_size <= 0:
        raise FileNotFoundError(f"Missing/empty PRISM ZIP: {p}")

    with rasterio.open(rec.dataset_locator) as ds:
        if ds.crs is None:
            raise RuntimeError(f"PRISM raster has no CRS: {rec.dataset_locator}")
        bundle = build_or_load_fraction(rec.dt.year, ds)
        if not grids_match_fraction_cache(ds, bundle, rec.dt.year):
            raise RuntimeError("PRISM rice-fraction cache grid mismatch")
        ma = ds.read(rec.band_index, window=bundle.window, masked=True)
        raw = np.asarray(ma.data)
        valid = ~np.ma.getmaskarray(ma)

        nodata = rec.source_nodata
        if nodata is None:
            nodata = ds.nodata
        if nodata is not None:
            valid &= raw != nodata

        scale = rec.source_scale
        offset = rec.source_offset
        if scale is None:
            try:
                scale = float(ds.scales[rec.band_index - 1])
            except Exception:
                scale = 1.0
        if offset is None:
            try:
                offset = float(ds.offsets[rec.band_index - 1])
            except Exception:
                offset = 0.0
        if not math.isfinite(scale):
            scale = 1.0
        if not math.isfinite(offset):
            offset = 0.0

        values = raw.astype("float32") * np.float32(scale) + np.float32(offset)
        valid &= np.isfinite(values)
        stats = weighted_stats(values, valid, bundle)

    key_text = f"{rec.element}|{rec.dt.isoformat()}|{rec.local_path}"
    return {
        "record_key": hashlib.sha1(key_text.encode("utf-8")).hexdigest(),
        "recorded_utc": utc_now(),
        "element": rec.element,
        "date": rec.dt.isoformat(),
        "year": rec.dt.year,
        "month": rec.dt.month,
        "unit": PRISM_UNITS[rec.element],
        "temporal_aggregation": PRISM_MONTHLY_AGG[rec.element],
        "local_path": rec.local_path,
        "dataset_locator": rec.dataset_locator,
        "rice_fraction_source": bundle.cache_path,
        **stats,
    }


