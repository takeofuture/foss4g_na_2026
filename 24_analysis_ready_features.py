def safe_float(v: object) -> Optional[float]:
    if v is None:
        return None
    s = str(v).strip()
    if not s or s.lower() in {"none", "nan", "null"}:
        return None
    try:
        x = float(s)
        return x if math.isfinite(x) else None
    except Exception:
        return None


def safe_int(v: object, default: int = 1) -> int:
    try:
        return int(float(str(v).strip()))
    except Exception:
        return default


