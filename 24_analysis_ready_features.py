"""
24_analysis_ready_features.py

California Rice Monitoring — Step 24

Purpose
-------
Build compact, analysis-ready feature tables for Colab from:

  * Step 23 statewide / tile remote-sensing summaries, and
  * PRISM daily 4 km RAW ZIP rasters from Step 20.

PRISM is processed on its own native grid.  The actual annual CDL rice mask
from Step 21 is averaged to the native PRISM grid to obtain annual rice
fraction; no PRISM raster is upsampled to MODIS resolution.  Daily PRISM
values are then rice-fraction x pixel-area weighted over California rice area.

The final products are intentionally small.  No full-size physical-value
raster archive is created.

Inputs
------
processed/23_rice_spatial_summary/_manifests/
    statewide_observation_summary.csv
    tile_observation_summary.csv
    run_summary.json
processed/21_cdl_rice/
    native_30m/<year>/rice_mask_<year>.tif
    _manifests/rice_area_by_year.csv
data/_manifests/band_grid_manifest.csv
    (PRISM /vsizip locators generated by Step 20)
data/prism_daily_4km/.../*.zip

Outputs
-------
processed/24_analysis_ready/
    monthly_features.parquet / .csv
    seasonal_features.parquet / .csv
    monthly_features_long.parquet / .csv
    seasonal_features_long.parquet / .csv
    tile_monthly_satellite.parquet / .csv
    _manifests/
        prism_daily_summary.csv
        feature_dictionary.csv
        monthly_quality.csv
        run_summary.json
    _work/
        prism_daily_observations.jsonl
        completed_prism_files.txt
        run_signature.json
    _cache/prism_rice_fraction/...

Temporal policy
---------------
* Spatial aggregation was already rice-area weighted in Step 23.
* For variables whose Step-23 temporal_aggregation is ``mean``, monthly means
  are pooled from sum_wx / valid_weight_m2 across observations.  This is an
  area-coverage-aware space-time mean rather than an unweighted mean of daily
  statewide means.
* For ET/PET/GPP/PsnNet (``sum``), monthly values are sums of the per-composite
  statewide weighted means.  Composite dates are assigned to the month of the
  product acquisition/composite-start date, matching the established project
  convention.
* PRISM precipitation is a monthly sum of daily rice-area weighted means.
  PRISM temperature/dew point/VPD variables are pooled daily means.
* Seasonal features aggregate April-November only.
* NTSG GPP and MOD17 GPP remain separate columns.  Step 24 does NOT fill the
  2019-2020 GPP gap and does NOT silently merge the two products.

Resume / smoke test
-------------------
PRISM has tens of thousands of ZIPs.  Each completed daily source file is
checkpointed.  A smoke test can therefore be followed by a full run without
reprocessing successful files.

Example smoke test:
    nohup python -u 24_analysis_ready_features.py --limit-prism-files 20 \
      > processed/24_analysis_ready/_manifests/24.log 2>&1 &

Full run after a successful smoke test:
    nohup python -u 24_analysis_ready_features.py \
      > processed/24_analysis_ready/_manifests/24.log 2>&1 &

Use --reset-prism-work only when intentionally rebuilding Step 24 from zero.
"""

